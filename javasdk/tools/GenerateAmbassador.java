import hla.rti1516e.RTIambassador;
import hla.rti1516e.exceptions.RTIinternalError;
import java.lang.reflect.Method;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.Comparator;
import java.util.Set;
import java.util.Map;
import java.util.LinkedHashMap;
import java.util.stream.Collectors;

/** Generates checked-exception adapters from the unchanged IEEE interface. */
public final class GenerateAmbassador {
    public static void main(String[] args) throws Exception {
        Path root = Path.of(args[0]);
        Map<String, String> implemented = new LinkedHashMap<>();
        for (String line : Files.readAllLines(root.resolve("tools/implemented-services.txt"))) {
            String entry = line.trim();
            if (entry.isEmpty() || entry.startsWith("#")) continue;
            int separator = entry.lastIndexOf('.');
            String name = separator < 0 ? entry : entry.substring(separator + 1);
            String receiver = separator < 0 ? "services" : "services." + entry.substring(0, separator);
            if (implemented.put(name, receiver) != null) throw new IllegalStateException("Duplicate mapped service: " + name);
        }
        StringBuilder out = new StringBuilder("// Generated by tools/GenerateAmbassador.java. Do not edit.\n"
                + "// API signatures: Reprinted with permission from IEEE 1516.1(TM)-2010.\n"
                + "package org.gorti.rti;\n\n"
                + "public final class GortiRtiAmbassador implements hla.rti1516e.RTIambassador {\n"
                + "    private final AmbassadorServices services = new AmbassadorServices();\n");
        Method[] methods = RTIambassador.class.getMethods();
        Arrays.sort(methods, Comparator.comparing(Method::toGenericString));
        StringBuilder inventory = new StringBuilder("# API signatures: Reprinted with permission from IEEE 1516.1(TM)-2010.\nstatus\tsignature\n");
        for (Method method : methods) {
            inventory.append(implemented.containsKey(method.getName()) ? "MAPPED" : "PENDING")
                    .append('\t').append(method.toGenericString()).append('\n');
            out.append("\n    @Override\n    public synchronized ").append(method.getReturnType().getCanonicalName())
                    .append(' ').append(method.getName()).append('(');
            Class<?>[] parameters = method.getParameterTypes();
            for (int i = 0; i < parameters.length; i++) {
                if (i > 0) out.append(", ");
                out.append(parameters[i].getCanonicalName()).append(" arg").append(i);
            }
            out.append(')');
            Class<?>[] exceptions = method.getExceptionTypes();
            if (exceptions.length != 0) {
                out.append(" throws ").append(Arrays.stream(exceptions).map(Class::getCanonicalName)
                        .collect(Collectors.joining(", ")));
            }
            out.append(" {\n");
            boolean internal = Arrays.asList(exceptions).contains(RTIinternalError.class);
            if (!implemented.containsKey(method.getName())) {
                out.append("        throw new ").append(internal ? "hla.rti1516e.exceptions.RTIinternalError" : "UnsupportedOperationException")
                        .append("(\"Java binding does not yet implement ").append(method.getName()).append("\");\n");
            } else {
                out.append("        try {\n            ");
                if (method.getReturnType() != void.class) out.append("return ");
                out.append(implemented.get(method.getName())).append('.').append(method.getName()).append('(');
                for (int i = 0; i < parameters.length; i++) {
                    if (i > 0) out.append(", ");
                    out.append("arg").append(i);
                }
                out.append(");\n        } catch (hla.rti1516e.exceptions.RTIexception failure) {\n");
                for (Class<?> exception : exceptions) {
                    out.append("            if (failure instanceof ").append(exception.getCanonicalName())
                            .append(") throw (").append(exception.getCanonicalName()).append(") failure;\n");
                }
                out.append("            throw new ")
                        .append(internal ? "hla.rti1516e.exceptions.RTIinternalError" : "IllegalStateException")
                        .append("(\"Undeclared service failure: \" + failure.getMessage(), failure);\n        }\n");
            }
            out.append("    }\n");
        }
        out.append("\n    public synchronized void enableOwnershipCallbackReceipts() throws hla.rti1516e.exceptions.RTIexception {\n"
                + "        services.enableOwnershipCallbackReceipts();\n    }\n"
                + "\n    public synchronized void retryOwnershipCallbacks() throws hla.rti1516e.exceptions.RTIexception {\n"
                + "        services.retryOwnershipCallbacks();\n    }\n");
        out.append("}\n");
        Path target = root.resolve("client/src/main/java/org/gorti/rti/GortiRtiAmbassador.java");
        Path coverage = root.resolve("service-coverage.tsv");
        if (args.length > 1 && args[1].equals("--check")) {
            if (!Files.readString(target).equals(out.toString())) throw new IllegalStateException("Regenerate GortiRtiAmbassador.java");
            if (!Files.readString(coverage).equals(inventory.toString())) throw new IllegalStateException("Regenerate service-coverage.tsv");
        } else {
            Files.createDirectories(target.getParent());
            Files.writeString(target, out, StandardCharsets.UTF_8);
            Files.writeString(coverage, inventory, StandardCharsets.UTF_8);
        }
    }
}
